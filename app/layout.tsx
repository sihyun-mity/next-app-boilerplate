import type { Metadata, Viewport } from 'next';
import { Geist, Geist_Mono } from 'next/font/google';
import { Suspense } from 'react';
import 'pretendard/dist/web/variable/pretendardvariable-dynamic-subset.css';
import '@/styles/globals.css';
import { MobileDetector, Polyfill } from '@/components';
import { QueryProvider } from '@/providers';
import { cn, staticMetadata } from '@/utils';

/**
 * create-next-app 템플릿의 Geist / Geist Mono 폰트.
 *
 * `variable` 옵션으로 CSS 변수만 html 에 선언하고, `styles/fonts.css` 의 `@theme inline` 에서
 * `font-sans` / `font-mono` 유틸리티에 연결한다. 기본 본문 폰트는 Pretendard 이므로, Geist 는
 * `font-sans` / `font-mono` 를 명시한 요소(예: 첫 화면)에만 적용된다.
 */
const geistSans = Geist({
  variable: '--font-geist-sans',
  subsets: ['latin'],
});

const geistMono = Geist_Mono({
  variable: '--font-geist-mono',
  subsets: ['latin'],
});

export const metadata: Metadata = staticMetadata({
  title: 'Create Next App',
  description: 'Generated by create next app',
});

export const viewport: Viewport = {
  width: 'device-width',
  initialScale: 1,
  userScalable: false,
  viewportFit: 'cover',
  interactiveWidget: 'resizes-content',
};

/**
 * App Router 의 루트 레이아웃.
 *
 * 모든 페이지를 감싸며, 다음 사이드 이펙트 / 마운트 포인트가 정해진 순서로 위치한다.
 * 1. `<Polyfill />` — core-js 폴리필을 가장 먼저 주입.
 * 2. `<QueryProvider>` — `@tanstack/react-query` 의 `QueryClientProvider`. Suspense 보다 바깥에 위치해야
 *    children 트리 어디서든 `useQuery` 가 동작한다.
 * 3. `<Suspense>{children}` — 페이지 트리. 로딩 경계의 기본 fallback 은 비워 둠.
 * 4. `<MobileDetector />` — User-Agent 분석 결과를 zustand 에 기록 (`isReady` 가 `true` 가 됨).
 * 5. `#next-app-portal` — `<Portal />` 컴포넌트가 children 을 포털링하는 마운트 포인트.
 *
 * html 은 `h-full`, body 는 `min-h-full flex flex-col` 로 잡아(최신 create-next-app 템플릿과 동일),
 * 페이지 최상위 요소가 `flex-1` 만으로 남은 높이를 채울 수 있게 한다. `100vh` 기반 `min-h-screen` 과 달리
 * 모바일 브라우저의 주소창 높이 변화에 영향을 받지 않는다.
 *
 * 상속되는 타이포그래피 설정은 html 에 둔다 — Geist 폰트 변수, Pretendard 가변 폰트(`font-pretendard`),
 * 한글 줄바꿈 규칙(`break-keep`, `wrap-anywhere`), `antialiased`. 포털 등 body 밖으로 렌더되는 요소와
 * `rem`/`em` 기준인 루트에서도 같은 타이포그래피가 적용된다.
 *
 * body 에는 레이아웃(`flex min-h-full flex-col`), 배경/전경색, 터치 팬 제스처 제한(`touch-pan-x touch-pan-y`),
 * 사용자 텍스트 선택 비활성화(`select-none`) 를 둔다. `touch-action` 은 상속되지 않고 html 에 두면 루트 스크롤
 * 제스처까지 바뀌므로 body 에 유지한다.
 *
 * Pretendard 는 `pretendard` npm 패키지의 dynamic subset CSS 를 import 한다. `unicode-range` 로 쪼개진
 * woff2 중 실제 페이지에 쓰인 글리프 구간만 내려받으므로, 한글 전체 폰트(약 2MB)를 한 번에 받지 않는다.
 */
export default function RootLayout({ children }: Readonly<LayoutProps<'/'>>) {
  return (
    <html
      lang="ko"
      className={cn(
        geistSans.variable,
        geistMono.variable,
        'h-full font-pretendard wrap-anywhere break-keep antialiased'
      )}
    >
      <body className="flex min-h-full touch-pan-x touch-pan-y flex-col bg-background text-foreground select-none">
        <Polyfill />

        <QueryProvider>
          <Suspense>{children}</Suspense>

          <MobileDetector />

          {/* For Portal Component */}
          <div id="next-app-portal" />
        </QueryProvider>
      </body>
    </html>
  );
}
